const WORD_COUNTS = [20, 30, 40, 60];

const rand = (n) => Math.floor(Math.random() * n);
const countWords = (s) => s.trim().split(/\s+/).filter(Boolean).length;

// Build a fresh text.
//   lang:      'bn' | 'en'
//   wordCount: a number (10-400), or anything else for a random 20 / 30 / 40 / 60
//   avoid:     a Set of lines used recently. They are skipped, so the same text does not return again and again.
//              (If nearly everything was used recently, the oldest lines may come back.)
// Returns { text, parts } where parts are the lines that were used.
function buildTextParts(lang = 'en', wordCount, avoid) {
  lang = lang === 'bn' ? 'bn' : 'en';
  const list = TEXTS[lang];
  const skip = avoid instanceof Set ? avoid : new Set();
  const n = parseInt(wordCount, 10);
  const target = n >= 10 && n <= 400 ? n : WORD_COUNTS[rand(WORD_COUNTS.length)];
  const limit = target * 1.25;

  const parts = [];
  let words = 0;
  const enough = () => words >= target * 0.9;

  // Walk through the list from a random place. Lines that are close together belong together,
  // so the text reads naturally. First only lines that were NOT used recently, then (if needed) the others.
  const start = rand(list.length);
  for (const pass of ['fresh', 'stale']) {
    for (let k = 0; k < list.length && !enough(); k++) {
      const line = list[(start + k) % list.length];
      if ((pass === 'fresh') === skip.has(line)) continue;
      const w = countWords(line);
      if (words + w > limit) continue; // this line is too long for what is left
      parts.push(line);
      words += w;
    }
  }
  if (!parts.length) {
    parts.push(list.reduce((a, b) => (countWords(a) <= countWords(b) ? a : b)));
  }
  return { text: parts.join(' '), parts };
}

function buildText(lang, wordCount, avoid) {
  return buildTextParts(lang, wordCount, avoid).text;
}

// 'bn' if the text contains any Bengali-script character, else 'en'
function detectLanguage(text) {
  return /[\u0980-\u09FF]/.test(text) ? 'bn' : 'en';
}

module.exports = { TEXTS, buildText, buildTextParts, detectLanguage };
